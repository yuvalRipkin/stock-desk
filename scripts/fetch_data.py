"""Download FinanceBench questions, document metadata and selected 10-K/10-Q PDFs.

Source: https://github.com/patronus-ai/financebench (CC BY-NC 4.0).

Usage:
    uv run python scripts/fetch_data.py            # use data_manifest.txt, or create it (top 5)
    uv run python scripts/fetch_data.py --top 10   # rebuild manifest from the 10 most-asked docs
    uv run python scripts/fetch_data.py --force    # re-download everything
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import sys
import tempfile
import time
from collections import Counter
from collections.abc import Callable
from pathlib import Path

import requests

BASE_URL = "https://raw.githubusercontent.com/patronus-ai/financebench/main"
JSONL_FILES = ["financebench_open_source.jsonl", "financebench_document_information.jsonl"]
QUESTIONS_FILE = "financebench_open_source.jsonl"
DEFAULT_TOP = 5

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "data"
PDF_DIR = DATA_DIR / "pdfs"
MANIFEST = ROOT / "data_manifest.txt"

MAX_ATTEMPTS = 3
BACKOFF_SECONDS = 1.0
TIMEOUT = (10, 120)  # connect, read
CHUNK_SIZE = 1 << 16

log = logging.getLogger("fetch_data")


class DownloadError(Exception):
    """A download that failed permanently (404, other 4xx, invalid content, retries exhausted)."""


# --- validation -------------------------------------------------------------------------------


def is_valid_pdf(path: Path) -> bool:
    try:
        with path.open("rb") as f:
            return f.read(4) == b"%PDF"
    except OSError:
        return False


def is_valid_jsonl(path: Path) -> bool:
    try:
        with path.open("r", encoding="utf-8") as f:
            json.loads(f.readline())
        return True
    except (OSError, UnicodeDecodeError, json.JSONDecodeError):
        return False


# --- download ---------------------------------------------------------------------------------


def _fetch_to(url: str, tmp_path: Path, session: requests.Session) -> None:
    """Stream url into tmp_path, retrying network errors and 5xx with exponential backoff."""
    for attempt in range(1, MAX_ATTEMPTS + 1):
        try:
            with session.get(url, stream=True, timeout=TIMEOUT) as resp:
                if resp.status_code == 404:
                    raise DownloadError(f"404 Not Found: {url}")
                if 400 <= resp.status_code < 500:
                    raise DownloadError(f"HTTP {resp.status_code}: {url}")
                resp.raise_for_status()  # 5xx -> HTTPError, retried below
                with tmp_path.open("wb") as f:
                    for chunk in resp.iter_content(CHUNK_SIZE):
                        f.write(chunk)
            return
        except DownloadError:
            raise
        except requests.RequestException as exc:
            if attempt == MAX_ATTEMPTS:
                raise DownloadError(f"gave up after {MAX_ATTEMPTS} attempts: {exc}") from exc
            delay = BACKOFF_SECONDS * 2 ** (attempt - 1)
            log.warning("retry %d/%d in %.0fs: %s", attempt, MAX_ATTEMPTS - 1, delay, exc)
            time.sleep(delay)


def download(
    url: str,
    dest: Path,
    validate: Callable[[Path], bool],
    session: requests.Session,
    force: bool,
) -> str:
    """Download url to dest atomically. Returns 'downloaded' or 'skipped'; raises DownloadError."""
    if not force and dest.exists() and validate(dest):
        return "skipped"

    dest.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(dir=dest.parent, prefix=f".{dest.name}.", suffix=".part")
    os.close(fd)
    tmp_path = Path(tmp_name)
    try:
        _fetch_to(url, tmp_path, session)
        if not validate(tmp_path):
            raise DownloadError(f"downloaded content is not valid: {url}")
        tmp_path.replace(dest)
    finally:
        tmp_path.unlink(missing_ok=True)
    return "downloaded"


# --- manifest ---------------------------------------------------------------------------------


def read_manifest(path: Path) -> list[str]:
    names: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        names.append(line.split("#", 1)[0].strip())
    return names


def build_manifest(questions_path: Path, top: int, out: Path) -> list[str]:
    counts: Counter[str] = Counter()
    with questions_path.open("r", encoding="utf-8") as f:
        for line in f:
            if line.strip():
                counts[json.loads(line)["doc_name"]] += 1

    ranked = sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[:top]
    width = max((len(name) for name, _ in ranked), default=0)
    lines = [
        "# FinanceBench documents to download (one doc_name per line).",
        f"# Generated by scripts/fetch_data.py --top {top}; edit freely.",
        *(f"{name:<{width}}  # {n} questions" for name, n in ranked),
    ]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    log.info("wrote %s (%d docs)", out.relative_to(ROOT), len(ranked))
    return [name for name, _ in ranked]


# --- main -------------------------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--top",
        type=int,
        metavar="N",
        help=f"rebuild data_manifest.txt from the N docs with the most questions "
        f"(default {DEFAULT_TOP} when no manifest exists)",
    )
    parser.add_argument("--force", action="store_true", help="re-download files that exist")
    args = parser.parse_args(argv)
    if args.top is not None and args.top < 1:
        parser.error("--top must be >= 1")

    logging.basicConfig(level=logging.INFO, format="%(message)s")
    results: dict[str, list[str]] = {"downloaded": [], "skipped": [], "failed": []}
    session = requests.Session()

    def fetch(url: str, dest: Path, validate: Callable[[Path], bool]) -> bool:
        rel = str(dest.relative_to(ROOT))
        try:
            status = download(url, dest, validate, session, args.force)
        except (DownloadError, OSError) as exc:
            log.error("failed      %s: %s", rel, exc)
            results["failed"].append(rel)
            return False
        log.info("%-11s %s", status, rel)
        results[status].append(rel)
        return True

    for name in JSONL_FILES:
        fetch(f"{BASE_URL}/data/{name}", DATA_DIR / name, is_valid_jsonl)

    questions_path = DATA_DIR / QUESTIONS_FILE
    doc_names: list[str] = []
    if args.top is not None or not MANIFEST.exists():
        if is_valid_jsonl(questions_path):
            doc_names = build_manifest(questions_path, args.top or DEFAULT_TOP, MANIFEST)
        else:
            log.error("cannot build manifest: %s is missing or invalid", QUESTIONS_FILE)
            results["failed"].append(str(MANIFEST.relative_to(ROOT)))
    else:
        doc_names = read_manifest(MANIFEST)
        log.info("using %s (%d docs)", MANIFEST.relative_to(ROOT), len(doc_names))

    for doc in doc_names:
        fetch(f"{BASE_URL}/pdfs/{doc}.pdf", PDF_DIR / f"{doc}.pdf", is_valid_pdf)

    log.info(
        "summary: %d downloaded, %d skipped, %d failed",
        len(results["downloaded"]),
        len(results["skipped"]),
        len(results["failed"]),
    )
    for rel in results["failed"]:
        log.info("  failed: %s", rel)
    return 1 if results["failed"] else 0


if __name__ == "__main__":
    sys.exit(main())
